import type { SupabaseClient } from "@supabase/supabase-js";
import { EMAIL_LOGO_B64, EMAIL_LOGO_CID } from "@/lib/groupmail/logo";
import { makeTransport, type SmtpAuth } from "@/lib/groupmail/send";

const NOTIFICATION_MESSAGE_ID_DOMAIN = "arabshipbroker.com";

export interface NotificationClaim {
  job_kind: "instant" | "digest";
  id: string;
  claim_token: string;
  attempts: number;
  recipient_user_id: string;
}

export interface NotificationSnapshot {
  id: string;
  recipient_user_id: string;
  importance: "urgent" | "normal" | "info";
  title: string;
  body: string;
  href: string | null;
  created_at: string;
  total_count: number;
}

export interface NotificationRecipient {
  id: string;
  email: string;
  full_name: string | null;
  is_active: boolean;
}

export interface NotificationMail {
  to: string;
  subject: string;
  html: string;
  text: string;
  messageId: string;
}

export interface NotificationDispatchResult {
  claimed: number;
  sent: number;
  retried: number;
  failed: number;
  suppressed: number;
  lost: number;
}

export interface DeliveryTransport {
  send(mail: NotificationMail): Promise<void>;
  close(): void;
}

export type SettleDelivery = (
  claim: NotificationClaim,
  outcome: "sent" | "failed" | "suppressed",
  error: string | null,
) => Promise<boolean>;

function escapeHtml(value: string): string {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

function safeMailSubject(value: string): string {
  const normalized = value.replace(/[\u0000-\u001f\u007f]+/g, " ").replace(/\s+/g, " ").trim();
  return normalized || "Arab ShipBroker notification";
}

function safeAbsoluteHref(siteUrl: string | null, href: string | null): string | null {
  if (!siteUrl || !href || !href.startsWith("/") || href.startsWith("//") || /[\\\u0000-\u001f\u007f]/.test(href)) return null;
  try {
    const base = new URL(siteUrl);
    const target = new URL(href, base);
    return target.origin === base.origin ? target.toString() : null;
  } catch {
    return null;
  }
}

